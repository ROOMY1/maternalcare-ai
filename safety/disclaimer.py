"""Fixed safety texts in English and Arabic: disclaimer, not-found message, dosage notice.

Purpose
    These sentences are added by code, never generated by the LLM, so they are always present
    and always worded the same way.

Author: Abdelrahman Islam.
"""

from __future__ import annotations

from typing import Literal

Lang = Literal["ar", "en"]

DISCLAIMER: dict[str, str] = {
    "en": (
        "Disclaimer: MaternalCare AI is an academic, supportive information tool. It is not a "
        "diagnostic tool and does not replace your obstetrician or midwife. Always discuss "
        "medical decisions, including any medicine, with your treating clinician. In an "
        "emergency, go to the nearest emergency department or call an ambulance (123 in Egypt)."
    ),
    "ar": (
        "تنبيه: MaternalCare AI أداة معلومات مساعدة لأغراض أكاديمية، وليست أداة تشخيص ولا "
        "تغني عن طبيب النساء والتوليد أو القابلة. ناقشي أي قرار طبي، بما في ذلك أي دواء، مع "
        "طبيبك المعالج. في الحالات الطارئة توجهي فوراً إلى أقرب طوارئ أو اتصلي بالإسعاف (123 في مصر)."
    ),
}

NOT_FOUND: dict[str, str] = {
    "en": "I could not find an answer to this question in the maternal-care guidelines I have.",
    "ar": "لم أجد إجابة لهذا السؤال في إرشادات رعاية الأمومة المتاحة لدي.",
}

DOSAGE_NOTICE: dict[str, str] = {
    "en": (
        "Dosing information has been removed: the dose, timing and any change of a medicine "
        "must be decided by your treating obstetrician."
    ),
    "ar": "تم حذف معلومات الجرعة: الجرعة وموعدها وأي تغيير فيها يحددها طبيب النساء المتابع لحالتك.",
}


EMERGENCY_BANNER: dict[str, str] = {
    "en": ("⚠️ POSSIBLE EMERGENCY: what you describe can be a danger sign. Go to the nearest "
           "emergency department now or call an ambulance (123 in Egypt). Do not wait for a clinic "
           "appointment."),
    "ar": ("⚠️ تنبيه طوارئ: اللي بتوصفيه ممكن يكون علامة خطر. روحي أقرب طوارئ فوراً أو كلّمي "
           "الإسعاف 123، ومتستنيش ميعاد العيادة."),
}

EMPTY_ANSWER: dict[str, str] = {
    "en": "The model returned an empty answer. Please ask the question again.",
    "ar": "النموذج لم يرجع إجابة. من فضلك اسألي السؤال مرة أخرى.",
}


GENERATION_FAILED: dict[str, str] = {
    "en": ("The model could not produce a clear answer from the guidelines for this question (it "
           "started repeating itself or mixing languages). Please try asking in different words, and "
           "discuss the question with your doctor."),
    "ar": ("النموذج لم يستطع إنتاج إجابة واضحة من الإرشادات لهذا السؤال (بدأ يكرر نفسه أو يخلط "
           "اللغات). من فضلك جربي صياغة مختلفة، وناقشي السؤال مع طبيبك."),
}


def get_emergency_banner(lang: Lang) -> str:
    """Return the emergency banner (shown above the answer when a danger sign is detected)."""
    return EMERGENCY_BANNER[lang]


def get_disclaimer(lang: Lang) -> str:
    """Return the disclaimer for `lang` ("ar" or "en")."""
    return DISCLAIMER[lang]


def get_not_found(lang: Lang) -> str:
    """Return the fixed "not found in the guidelines" sentence for `lang`."""
    return NOT_FOUND[lang]


def get_dosage_notice(lang: Lang) -> str:
    """Return the sentence that replaces dose-containing sentences."""
    return DOSAGE_NOTICE[lang]


def add_disclaimer(answer: str, lang: Lang) -> str:
    """Append the disclaimer to an answer (done by code on every answer)."""
    return f"{answer.rstrip()}\n\n---\n{DISCLAIMER[lang]}"
